def detail_block(did):
    global POSTER
    i = cat.index(f'<h3 id="{did}">')
    j = cat.index('</h3>', i) + 5
    m = re.search(r'\n<h3 id=|\n<h2', cat[j:])
    blk = cat[j:j + m.start()].strip()
    fig = re.search(r'<figure class="pshow[^"]*"[^>]*>.*?</figure>', blk, re.S)
    if fig:
        POSTER = fig.group(0)
        blk = blk.replace(fig.group(0), '').strip()
    return blk

