def poster_cfg(slug):
    """Poster settings for a product, if its posters have been generated by design/poster-template/poster.py."""
    f = os.path.join(POSTER_DIR, slug + '.json')
    if not os.path.exists(f): return None
    c = json.load(open(f))
    first = f"{ROOT}/images/products/{slug}-{c['packs'][0]}kg-v{c['version']}.webp"
    return c if os.path.exists(first) else None

